//! Generates the logo's derived files from `logo/mark.svg`: the board's I4 bitmap
//! (`firmware/main/logo_img.{c,h}`), the app's copies of the mark, and the icon set that
//! `tauri icon` wrote, pruned to what the desktop bundle lists. With `--check` it writes
//! nothing and fails if any text output differs from a fresh generation. Run it through
//! `mise run logo:gen` and `mise run logo:check`.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use resvg::{tiny_skia, usvg};

/// Side of the board's bitmap, in pixels. The boot screen and the sleep screen draw it at this size.
const DEVICE_PX: u32 = 240;

/// The two colors of the mark, straight RGB: the panel and the lit key.
const PANEL: [u8; 3] = [0xe7, 0xed, 0xf3];
const KEY: [u8; 3] = [0x38, 0xbd, 0xf8];

/// LVGL's I4 palette has 16 entries, each B, G, R, A in four bytes, placed before the pixels.
const PALETTE_LEN: usize = 16;

const HEADER: &str = "\
/* Generated by `mise run logo:gen` from logo/mark.svg. Do not edit. */
#pragma once

#include \"lvgl.h\"

/* The mark, 240 px square, as I4: a 16-entry palette of the panel and the key, clear outside. */
extern const lv_image_dsc_t wd_logo;
";

struct Output {
    path: PathBuf,
    bytes: Vec<u8>,
}

fn main() -> ExitCode {
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    match run(check) {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("logo_gen: {message}");
            ExitCode::FAILURE
        }
    }
}

fn run(check: bool) -> Result<(), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .map_err(|e| format!("can't find the repo root: {e}"))?;
    let mark_path = root.join("logo/mark.svg");
    let mark =
        fs::read(&mark_path).map_err(|e| format!("can't read {}: {e}", mark_path.display()))?;

    let mut stale = Vec::new();
    for output in outputs(&root, &mark)? {
        if check {
            if fs::read(&output.path).ok().as_deref() != Some(output.bytes.as_slice()) {
                stale.push(output.path);
            }
        } else {
            fs::write(&output.path, &output.bytes)
                .map_err(|e| format!("can't write {}: {e}", output.path.display()))?;
            eprintln!("wrote {}", output.path.display());
        }
    }

    if check {
        if stale.is_empty() {
            return Ok(());
        }
        let list: Vec<String> = stale.iter().map(|p| p.display().to_string()).collect();
        return Err(format!(
            "out of date: {}. Run mise run logo:gen.",
            list.join(", ")
        ));
    }
    prune_icons(&root)
}

fn outputs(root: &Path, mark: &[u8]) -> Result<Vec<Output>, String> {
    let pixels = render_indices(mark, DEVICE_PX)?;
    let i4 = pack_i4(&pixels, DEVICE_PX, DEVICE_PX);
    Ok(vec![
        Output {
            path: root.join("firmware/main/logo_img.c"),
            bytes: c_source(&palette(), &i4).into_bytes(),
        },
        Output {
            path: root.join("firmware/main/logo_img.h"),
            bytes: HEADER.as_bytes().to_vec(),
        },
        Output {
            path: root.join("app/src/assets/logo.svg"),
            bytes: mark.to_vec(),
        },
        Output {
            path: root.join("app/public/favicon.svg"),
            bytes: mark.to_vec(),
        },
    ])
}

/// Deletes what `tauri icon` writes beyond the desktop bundle: the mobile sets and the Store
/// logos. The files `bundle.icon` lists stay, and so does `icon.png`, which the tray uses as its
/// default window icon.
fn prune_icons(root: &Path) -> Result<(), String> {
    let conf_path = root.join("app/src-tauri/tauri.conf.json");
    let conf_text = fs::read_to_string(&conf_path)
        .map_err(|e| format!("can't read {}: {e}", conf_path.display()))?;
    let conf: serde_json::Value = serde_json::from_str(&conf_text)
        .map_err(|e| format!("can't parse {}: {e}", conf_path.display()))?;
    let listed = conf["bundle"]["icon"]
        .as_array()
        .ok_or("tauri.conf.json has no bundle.icon list")?;
    let mut keep: Vec<String> = listed
        .iter()
        .filter_map(|v| v.as_str())
        .filter_map(|s| s.strip_prefix("icons/"))
        .map(str::to_owned)
        .collect();
    keep.push("icon.png".to_owned());

    let icons = root.join("app/src-tauri/icons");
    let entries =
        fs::read_dir(&icons).map_err(|e| format!("can't read {}: {e}", icons.display()))?;
    for entry in entries {
        let entry = entry.map_err(|e| format!("can't read {}: {e}", icons.display()))?;
        let name = entry.file_name().to_string_lossy().into_owned();
        if keep.contains(&name) {
            continue;
        }
        let path = entry.path();
        let removed = if path.is_dir() {
            fs::remove_dir_all(&path)
        } else {
            fs::remove_file(&path)
        };
        removed.map_err(|e| format!("can't remove {}: {e}", path.display()))?;
        eprintln!("removed {}", path.display());
    }
    Ok(())
}

/// Renders the SVG square at `px` as straight (un-premultiplied) RGBA, row by row.
fn render_rgba(svg: &[u8], px: u32) -> Result<Vec<[u8; 4]>, String> {
    let tree = usvg::Tree::from_data(svg, &usvg::Options::default())
        .map_err(|e| format!("can't read the SVG: {e}"))?;
    let size = tree.size();
    let mut pixmap = tiny_skia::Pixmap::new(px, px).ok_or("no pixmap for the logo size")?;
    let transform =
        tiny_skia::Transform::from_scale(px as f32 / size.width(), px as f32 / size.height());
    resvg::render(&tree, transform, &mut pixmap.as_mut());
    Ok(pixmap
        .data()
        .as_chunks::<4>()
        .0
        .iter()
        .map(|p| {
            // resvg gives premultiplied color. Clear pixels carry no color, so they stay zero.
            let a = u32::from(p[3]);
            if a == 0 {
                return [0, 0, 0, 0];
            }
            let c = |v: u8| ((u32::from(v) * 255 + a / 2) / a).min(255) as u8;
            [c(p[0]), c(p[1]), c(p[2]), p[3]]
        })
        .collect())
}

/// The 16 palette entries as straight RGBA. Entry 0 is clear. Entries 1 to 8 are the panel at
/// eight alpha levels, which the antialiased outer and hole edges quantize to. Entries 9 to 11 are
/// the panel blended toward the key at a quarter, half and three quarters, which the key's edge
/// quantizes to over the opaque panel. Entry 12 is the key. The rest are clear.
fn palette() -> [[u8; 4]; PALETTE_LEN] {
    let mut p = [[0u8; 4]; PALETTE_LEN];
    for (level, entry) in p.iter_mut().enumerate().skip(1).take(8) {
        let alpha = (level * 255 / 8) as u8;
        *entry = [PANEL[0], PANEL[1], PANEL[2], alpha];
    }
    for t in 1..=3u32 {
        let mix =
            |k: usize| ((u32::from(PANEL[k]) * (4 - t) + u32::from(KEY[k]) * t + 2) / 4) as u8;
        p[8 + t as usize] = [mix(0), mix(1), mix(2), 255];
    }
    p[12] = [KEY[0], KEY[1], KEY[2], 255];
    p
}

/// The palette index whose entry is nearest to `px` in RGBA. A tie goes to the lower index.
fn nearest(px: [u8; 4], palette: &[[u8; 4]; PALETTE_LEN]) -> u8 {
    let mut best = (i64::MAX, 0usize);
    for (i, entry) in palette.iter().enumerate() {
        let d: i64 = (0..4)
            .map(|c| {
                let x = i64::from(px[c]) - i64::from(entry[c]);
                x * x
            })
            .sum();
        if d < best.0 {
            best = (d, i);
        }
    }
    best.1 as u8
}

/// Renders the SVG square at `px` and quantizes each pixel to a palette index, row by row.
fn render_indices(svg: &[u8], px: u32) -> Result<Vec<u8>, String> {
    let palette = palette();
    Ok(render_rgba(svg, px)?
        .into_iter()
        .map(|p| nearest(p, &palette))
        .collect())
}

/// Packs palette indices into LVGL's I4 layout: two pixels a byte, the left one in the high
/// nibble, and each row starting on a byte. An odd width leaves the last low nibble zero.
fn pack_i4(indices: &[u8], width: u32, height: u32) -> Vec<u8> {
    let (width, height) = (width as usize, height as usize);
    let stride = width.div_ceil(2);
    let mut out = vec![0u8; stride * height];
    for y in 0..height {
        for x in 0..width {
            let index = indices[y * width + x];
            let byte = &mut out[y * stride + x / 2];
            if x % 2 == 0 {
                *byte |= index << 4;
            } else {
                *byte |= index;
            }
        }
    }
    out
}

fn c_source(palette: &[[u8; 4]; PALETTE_LEN], i4: &[u8]) -> String {
    let mut src = String::new();
    src.push_str("/* Generated by `mise run logo:gen` from logo/mark.svg. Do not edit. */\n");
    src.push_str("#include \"logo_img.h\"\n\n");
    src.push_str("static const uint8_t wd_logo_map[] = {\n");
    // The palette, 16 entries of B, G, R, A, then the pixels, two a byte.
    let bytes: Vec<u8> = palette
        .iter()
        .flat_map(|e| [e[2], e[1], e[0], e[3]])
        .chain(i4.iter().copied())
        .collect();
    for (n, row) in bytes.chunks(16).enumerate() {
        if n * 16 == PALETTE_LEN * 4 {
            src.push_str("    /* pixels */\n");
        }
        src.push_str("   ");
        for byte in row {
            let _ = write!(src, " 0x{byte:02x},");
        }
        src.push('\n');
    }
    src.push_str("};\n\n");
    src.push_str("const lv_image_dsc_t wd_logo = {\n");
    src.push_str("    .header = {\n");
    src.push_str("        .magic = LV_IMAGE_HEADER_MAGIC,\n");
    src.push_str("        .cf = LV_COLOR_FORMAT_I4,\n");
    let _ = writeln!(src, "        .w = {DEVICE_PX},");
    let _ = writeln!(src, "        .h = {DEVICE_PX},");
    let _ = writeln!(src, "        .stride = {},", DEVICE_PX.div_ceil(2));
    src.push_str("    },\n");
    src.push_str("    .data_size = sizeof(wd_logo_map),\n");
    src.push_str("    .data = wd_logo_map,\n");
    src.push_str("};\n");
    src
}

#[cfg(test)]
mod tests {
    use super::*;

    const MARK: &[u8] = include_bytes!("../../../logo/mark.svg");

    fn square(view: &str, rect: &str) -> Vec<u8> {
        format!(r##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view}">{rect}</svg>"##)
            .into_bytes()
    }

    /// The panel's palette index, the one that is the panel at full alpha.
    const PANEL_SOLID: u8 = 8;

    #[test]
    fn half_filled_square_packs_high_nibble_first() {
        // Left two columns panel, right two clear: each row is one 0x88 byte then one 0x00.
        let svg = square("4 4", r##"<rect width="2" height="4" fill="#e7edf3"/>"##);
        let pixels = render_indices(&svg, 4).unwrap();
        assert_eq!(pack_i4(&pixels, 4, 4), [0x88, 0x00].repeat(4));
    }

    #[test]
    fn odd_width_rows_start_on_a_byte() {
        // Three panel pixels: the third one's low nibble is padding and stays zero.
        let svg = square("3 1", r##"<rect width="3" height="1" fill="#e7edf3"/>"##);
        let pixels = render_indices(&svg, 3).unwrap();
        assert_eq!(pack_i4(&pixels, 3, 1), [0x88, 0x80]);
    }

    #[test]
    fn palette_is_stored_blue_green_red_alpha() {
        let p = palette();
        assert_eq!(p[0], [0, 0, 0, 0]);
        // The key is #38bdf8, so its bytes are f8 bd 38 ff.
        let mut bytes = Vec::new();
        bytes.extend([p[12][2], p[12][1], p[12][0], p[12][3]]);
        assert_eq!(bytes, [0xf8, 0xbd, 0x38, 0xff]);
    }

    #[test]
    fn an_antialiased_panel_edge_maps_to_a_partial_entry() {
        // Panel at half alpha is entry 4 (alpha 127), the nearest level.
        assert_eq!(nearest([0xe7, 0xed, 0xf3, 128], &palette()), 4);
        // A pixel near full key blue is the key itself.
        assert_eq!(nearest([0x38, 0xbd, 0xf8, 250], &palette()), 12);
    }

    #[test]
    fn mark_shows_the_key_as_its_own_color_and_the_gaps_clear() {
        let pixels = render_indices(MARK, DEVICE_PX).unwrap();
        let i4 = pack_i4(&pixels, DEVICE_PX, DEVICE_PX);
        let stride = DEVICE_PX.div_ceil(2) as usize;
        // The lit key's center, (762, 377) of the 1024 viewBox, is pixel (178, 88) at 240 px.
        assert_eq!(i4[88 * stride + 178 / 2] >> 4, 12);
        // The top-left key's hole, centered at (262, 377), is pixel (61, 88): clear.
        assert_eq!(i4[88 * stride + 61 / 2] & 0x0F, 0);
        // The body between two keys, (380, 377), is pixel (89, 88): the panel at full alpha.
        assert_eq!(i4[88 * stride + 89 / 2] & 0x0F, PANEL_SOLID);
    }

    #[test]
    fn c_source_declares_i4_with_palette_and_pixels() {
        let src = c_source(&palette(), &[0xAB; 120]);
        assert!(src.contains(".cf = LV_COLOR_FORMAT_I4"));
        assert!(src.contains(".stride = 120"));
        assert!(src.contains("sizeof(wd_logo_map)"));
        assert!(src.contains("/* pixels */"));
        assert!(src.contains("0xab,"));
    }
}
