#!/usr/bin/env node
// Generates every font output from fonts/fonts.json and the checked-in TTFs. See plans/fonts.md.
//
//   node fonts/generate.mjs            write the outputs into the tree (mise run fonts:gen)
//   node fonts/generate.mjs --check    generate into a temp dir and fail if the tree differs
//                                      (mise run fonts:check)
//   node fonts/generate.mjs --probe    print the largest --size per slot whose line_height fits
//   node fonts/generate.mjs --stats    print the bytes of the generated arrays
//
// It reads only committed files and never downloads. The formatters (biome, rustfmt, clang-format)
// come from PATH, so run it through mise.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const FONTS_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(FONTS_DIR, "..");
const LV_FONT_CONV = join(
  FONTS_DIR,
  "node_modules/lv_font_conv/lv_font_conv.js",
);

// The two text slots, named by their Montserrat size. `box` is the line box the layout uses for
// every font, `min` the smallest line_height that still gives the slot's line count in a fixed box
// (plans/fonts.md, Geometry). A slot-32 icon label is 2 lines in 70 px, so floor(70 / lh) must be 2.
const SLOTS = {
  24: { box: 27, min: 14 },
  32: { box: 35, min: 24 },
};
const RANGE = "0x20-0x7E";
const GLYPHS = 95;
const OUT_C = "firmware/main/fonts";
const OUT_LIST = "firmware/main/font_list.h";
const OUT_TS = "app/src/fonts.gen.ts";
const OUT_RS = "app/src-tauri/src/daemon/fonts_gen.rs";
const HEADER =
  "Generated by fonts/generate.mjs (mise run fonts:gen). Do not edit.";

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");
const ident = (id) => id.replaceAll("-", "_");
const cName = (font, slot) => `wd_font_${ident(font.id)}_${slot}`;
const chromeName = (chrome) => `wd_font_${ident(chrome.id)}`;

function die(msg) {
  console.error(`fonts: ${msg}`);
  process.exit(1);
}

function loadManifest() {
  const manifest = JSON.parse(
    readFileSync(join(FONTS_DIR, "fonts.json"), "utf8"),
  );
  const pkg = JSON.parse(readFileSync(join(FONTS_DIR, "package.json"), "utf8"));
  if (pkg.devDependencies?.lv_font_conv !== manifest.lv_font_conv) {
    die(
      `package.json pins lv_font_conv ${pkg.devDependencies?.lv_font_conv}, manifest says ${manifest.lv_font_conv}`,
    );
  }
  if (manifest.range !== RANGE)
    die(`manifest range ${manifest.range} is not ${RANGE}`);
  if (!existsSync(LV_FONT_CONV))
    die(
      "fonts/node_modules is missing; run `pnpm --dir fonts install --frozen-lockfile`",
    );
  for (const font of manifest.fonts) {
    if (font.fallback) {
      font.fallback.source = manifest.fonts.find(
        (f) => f.id === font.fallback.font,
      );
      if (!font.fallback.source)
        die(
          `${font.id}: fallback font ${font.fallback.font} is not in the manifest`,
        );
    }
    // Nothing but the pinned font and license, and the chrome weights of its family, may sit in a font's directory.
    const have = readdirSync(join(FONTS_DIR, font.id)).sort();
    const expected = [
      font.file,
      font.license.file,
      ...manifest.chrome.filter((c) => c.family === font.id).map((c) => c.file),
    ].sort();
    if (have.join() !== expected.join())
      die(`fonts/${font.id}/ holds [${have}], expected [${expected}]`);
    for (const [what, path, want] of [
      ["font", join(FONTS_DIR, font.id, font.file), font.sha256],
      [
        "license",
        join(FONTS_DIR, font.id, font.license.file),
        font.license.sha256,
      ],
    ]) {
      if (!existsSync(path)) die(`${relative(ROOT, path)} is missing`);
      const got = sha256(readFileSync(path));
      if (got !== want)
        die(
          `${relative(ROOT, path)}: ${what} sha256 is ${got}, manifest says ${want}`,
        );
    }
  }
  for (const c of manifest.chrome) {
    c.family = manifest.fonts.find((f) => f.id === c.family);
    if (!c.family)
      die(`chrome font ${c.id}: its family is not in the manifest`);
    const path = join(FONTS_DIR, c.family.id, c.file);
    if (!existsSync(path)) die(`${relative(ROOT, path)} is missing`);
    const got = sha256(readFileSync(path));
    if (got !== c.sha256)
      die(
        `${relative(ROOT, path)}: font sha256 is ${got}, manifest says ${c.sha256}`,
      );
  }
  const known = new Set([
    "node_modules",
    "fonts.json",
    "generate.mjs",
    "package.json",
    "pnpm-lock.yaml",
    ...manifest.fonts.map((f) => f.id),
  ]);
  const stray = readdirSync(FONTS_DIR).filter((name) => !known.has(name));
  if (stray.length > 0) die(`unexpected entries in fonts/: ${stray}`);
  return manifest;
}

// Runs lv_font_conv in a fresh directory holding only the TTF, with bare file names, so the `Opts:`
// line in the output doesn't depend on where the tree or the temp dir is.
function convert(font, slot, size) {
  const work = mkdtempSync(join(tmpdir(), "wd-font-"));
  try {
    const name = cName(font, slot);
    copyFileSync(join(FONTS_DIR, font.id, font.file), join(work, font.file));
    // A font missing some codepoints takes them from its fallback font, in the same output.
    const fb = font.fallback;
    const fonts = [["--font", font.file, "-r", fb ? fb.primary_range : RANGE]];
    if (fb) {
      copyFileSync(
        join(FONTS_DIR, fb.source.id, fb.source.file),
        join(work, fb.source.file),
      );
      fonts.push(["--font", fb.source.file, "-r", fb.range]);
    }
    return runConv(work, fonts, name, size);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

function runConv(work, fonts, name, size) {
  execFileSync(
    process.execPath,
    [
      LV_FONT_CONV,
      ...fonts.flat(),
      "--size",
      String(size),
      "--bpp",
      "4",
      "--no-compress",
      "--no-prefilter",
      "--force-fast-kern-format",
      "--format",
      "lvgl",
      "--lv-include",
      "lvgl.h",
      "--lv-font-name",
      name,
      "-o",
      `${name}.c`,
    ],
    { cwd: work, stdio: ["ignore", "ignore", "inherit"] },
  );
  return readFileSync(join(work, `${name}.c`), "utf8");
}

// A chrome font: one weight of a family, one size, its own range.
function convertChrome(chrome) {
  const work = mkdtempSync(join(tmpdir(), "wd-font-"));
  try {
    copyFileSync(
      join(FONTS_DIR, chrome.family.id, chrome.file),
      join(work, chrome.file),
    );
    return runConv(
      work,
      [["--font", chrome.file, "-r", chrome.range]],
      chromeName(chrome),
      chrome.size,
    );
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

// A font with no kerning pairs (a monospace one) has no kern arrays, so they are optional.
function arrayBody(c, decl, optional = false) {
  const start = c.indexOf(decl);
  if (start < 0) {
    if (optional) return "";
    die(`generated C has no ${decl}`);
  }
  const open = c.indexOf("{", start);
  return c.slice(open + 1, c.indexOf("};", open));
}

// Reads the numbers the app and the checks need out of lv_font_conv's C.
function parse(c, name) {
  const lineHeight = Number(/\.line_height = (\d+),/.exec(c)?.[1]);
  const glyphs = [
    ...c.matchAll(/\{\.bitmap_index = \d+, \.adv_w = (\d+),/g),
  ].map((m) => Number(m[1]));
  // Entry 0 is LVGL's reserved "id = 0" glyph; the others follow the `U+XXXX` comments in order.
  const codes = [...c.matchAll(/\/\* U\+([0-9A-F]+) /g)].map((m) =>
    parseInt(m[1], 16),
  );
  if (codes.length !== glyphs.length - 1)
    die(`${codes.length} glyph comments for ${glyphs.length - 1} glyphs`);
  // Every codepoint of the range must have a glyph, else LVGL would draw a placeholder box for it.
  // A font that lacks some gets them from its manifest `fallback`.
  const advOf = new Map(codes.map((code, i) => [code, glyphs[i + 1]]));
  const absent = Array.from({ length: GLYPHS }, (_, i) => 0x20 + i).filter(
    (code) => !advOf.has(code),
  );
  if (absent.length > 0)
    die(
      `${name} lacks codepoints [${absent.map((n) => `0x${n.toString(16)}`)}]`,
    );
  const adv = Array.from({ length: GLYPHS }, (_, i) => advOf.get(0x20 + i));
  const count = (decl, optional) =>
    arrayBody(c, decl, optional)
      .replace(/\/\*.*?\*\//gs, "")
      .match(/-?\b(?:0x[0-9a-f]+|\d+)\b/gi)?.length ?? 0;
  const bytes = {
    glyph_bitmap: count("glyph_bitmap[] ="),
    glyph_dsc: glyphs.length * 8, // sizeof(lv_font_fmt_txt_glyph_dsc_t)
    kern_left_class_mapping: count("kern_left_class_mapping[] =", true),
    kern_right_class_mapping: count("kern_right_class_mapping[] =", true),
    kern_class_values: count("kern_class_values[] =", true),
  };
  if (!lineHeight) die("no line_height in generated C");
  return { lineHeight, adv, bytes, codes: new Set(codes) };
}

function checkSlot(font, slot, nominal, size, lineHeight) {
  const { box, min } = SLOTS[slot];
  if (size > nominal)
    die(
      `${font.id} slot ${slot}: --size ${size} is above the nominal ${nominal}`,
    );
  if (lineHeight > box || lineHeight < min) {
    die(
      `${font.id} slot ${slot}: line_height ${lineHeight} at --size ${size} is outside ${min}..${box}`,
    );
  }
}

// Prepends the family's notice and normalizes whitespace so the builtin hooks leave the file alone.
function finishC(font, slot, c) {
  const credit = (f) => [
    ` * ${f.copyright}`,
    ` * SPDX-License-Identifier: ${f.license.spdx}`,
    ` * License text: fonts/${f.id}/${f.license.file}`,
  ];
  const fb = font.fallback;
  const note = [
    `/* ${HEADER}`,
    ` * ${font.name} Medium, slot ${slot}.`,
    ...credit(font),
    ...(fb
      ? [
          ` * ${fb.range} comes from ${fb.source.name} Medium:`,
          ...credit(fb.source),
        ]
      : []),
    " */",
    "",
  ].join("\n");
  const body = `${note}\n${c}`
    .split("\n")
    .map((line) => line.replace(/[ \t]+$/, ""))
    .join("\n")
    .replace(/\n+$/, "");
  return `${body}\n`;
}

function finishChromeC(chrome, c) {
  const f = chrome.family;
  const note = [
    `/* ${HEADER}`,
    ` * ${f.name} ${chrome.file.replace(/^.*-(\w+)\.ttf$/, "$1")}, size ${chrome.size}, range ${chrome.range}: the device's bar.`,
    ` * ${f.copyright}`,
    ` * SPDX-License-Identifier: ${f.license.spdx}`,
    ` * License text: fonts/${f.id}/${f.license.file}`,
    " */",
    "",
  ].join("\n");
  const body = `${note}\n${c}`
    .split("\n")
    .map((line) => line.replace(/[ \t]+$/, ""))
    .join("\n")
    .replace(/\n+$/, "");
  return `${body}\n`;
}

function pipe(cmd, args, input, cwd) {
  return execFileSync(cmd, args, { input, cwd, encoding: "utf8" });
}

function fontListH(fonts) {
  const rows = [{ id: "montserrat" }, ...fonts].map(
    (f) => `    X(${ident(f.id)}, "${f.id}")`,
  );
  const src = [
    `/* ${HEADER} */`,
    "#pragma once",
    "",
    "/* The font ids of config.toml and the wire, in enum order. Montserrat is LVGL's built-in. */",
    `#define WD_FONT_LIST(X) \\\n${rows.join(" \\\n")}`,
    "",
  ].join("\n");
  return pipe("clang-format", ["--assume-filename=font_list.h"], src, ROOT);
}

function fontsCmake(fonts, chrome) {
  const files = [
    ...fonts.flatMap((f) =>
      Object.keys(SLOTS).map((slot) => `    fonts/${cName(f, slot)}.c`),
    ),
    ...chrome.map((c) => `    fonts/${chromeName(c)}.c`),
  ];
  return `# ${HEADER}\nset(WD_FONT_SRCS\n${files.join("\n")}\n)\n`;
}

function fontsTs(fonts, parsed) {
  const slotSrc = (f, slot) => {
    const p = parsed.get(`${f.id}/${slot}`);
    return `{ px: ${f.sizes[slot]}, lineHeight: ${p.lineHeight}, adv: [${p.adv.join(", ")}] }`;
  };
  const rows = fonts.map(
    (f) =>
      `  { id: ${JSON.stringify(f.id)}, name: ${JSON.stringify(f.name)}, slot24: ${slotSrc(f, 24)}, slot32: ${slotSrc(f, 32)} },`,
  );
  const src = [
    `// ${HEADER}`,
    "",
    'import type { Font } from "./montserrat";',
    "",
    "/** `px` is the lv_font_conv size; `lineHeight` and `adv` (1/16 px, ASCII 0x20 to 0x7e) are as in the generated C. */",
    "export type GeneratedSlot = Font & { px: number };",
    "",
    "/** Slot 24 has a 27 px line box and slot 32 a 35 px one, for every font. `name` is also the CSS family. */",
    "export type GeneratedFont = {",
    "  id: string;",
    "  name: string;",
    "  slot24: GeneratedSlot;",
    "  slot32: GeneratedSlot;",
    "};",
    "",
    "export const GENERATED_FONTS: readonly GeneratedFont[] = [",
    ...rows,
    "];",
    "",
  ].join("\n");
  return pipe(
    "biome",
    ["format", "--stdin-file-path=src/fonts.gen.ts"],
    src,
    join(ROOT, "app"),
  );
}

function fontsRs(fonts) {
  const ids = ["montserrat", ...fonts.map((f) => f.id)];
  const src = [
    `// ${HEADER}`,
    "",
    "/// Every font id `config.toml` accepts, Montserrat first.",
    `pub const FONT_IDS: [&str; ${ids.length}] = [${ids.map((id) => JSON.stringify(id)).join(", ")}];`,
    "",
  ].join("\n");
  return pipe(
    "rustfmt",
    ["--edition", "2021"],
    src,
    join(ROOT, "app/src-tauri"),
  );
}

function generate(manifest) {
  const outputs = new Map();
  const parsed = new Map();
  for (const font of manifest.fonts) {
    for (const slot of Object.keys(SLOTS)) {
      const size = font.sizes[slot];
      const c = convert(font, slot, size);
      const p = parse(c, `${font.id} slot ${slot}`);
      checkSlot(font, slot, Number(slot), size, p.lineHeight);
      parsed.set(`${font.id}/${slot}`, p);
      outputs.set(`${OUT_C}/${cName(font, slot)}.c`, finishC(font, slot, c));
    }
  }
  for (const chrome of manifest.chrome) {
    const c = convertChrome(chrome);
    const p = parse(c, `chrome ${chrome.id}`);
    if (p.lineHeight > SLOTS[24].box)
      die(
        `chrome ${chrome.id}: line_height ${p.lineHeight} is above the ${SLOTS[24].box} px line box`,
      );
    // The range may add codepoints beyond ASCII (the bar's degree sign); each must have a glyph.
    for (const code of chromeCodes(chrome.range))
      if (!p.codes.has(code))
        die(`chrome ${chrome.id} lacks U+${code.toString(16)}`);
    parsed.set(`chrome/${chrome.id}`, p);
    outputs.set(`${OUT_C}/${chromeName(chrome)}.c`, finishChromeC(chrome, c));
  }
  outputs.set(
    `${OUT_C}/fonts.cmake`,
    fontsCmake(manifest.fonts, manifest.chrome),
  );
  outputs.set(OUT_LIST, fontListH(manifest.fonts));
  outputs.set(OUT_TS, fontsTs(manifest.fonts, parsed));
  outputs.set(OUT_RS, fontsRs(manifest.fonts));
  return { outputs, parsed };
}

// "0x20-0x7E,0xB0" as the codepoints it names.
function chromeCodes(range) {
  return range.split(",").flatMap((part) => {
    const [lo, hi = lo] = part.split("-").map(Number);
    return Array.from({ length: hi - lo + 1 }, (_, i) => lo + i);
  });
}

function probe(manifest) {
  for (const font of manifest.fonts) {
    for (const slot of Object.keys(SLOTS)) {
      const { box, min } = SLOTS[slot];
      let found = null;
      for (let size = Number(slot); size >= 8 && !found; size--) {
        const { lineHeight } = parse(
          convert(font, slot, size),
          `${font.id} slot ${slot}`,
        );
        if (lineHeight <= box) found = { size, lineHeight };
      }
      const ok = found && found.lineHeight >= min;
      console.log(
        `${font.id} slot ${slot}: size ${found?.size} line_height ${found?.lineHeight} ${ok ? "ok" : "OUT OF RANGE"}`,
      );
    }
  }
}

function stats(parsed) {
  let total = 0;
  const byArray = {};
  for (const [key, p] of parsed) {
    const sum = Object.values(p.bytes).reduce((a, b) => a + b, 0);
    total += sum;
    for (const [name, n] of Object.entries(p.bytes))
      byArray[name] = (byArray[name] ?? 0) + n;
    console.log(
      `${key.padEnd(16)} ${String(sum).padStart(7)} B  ${JSON.stringify(p.bytes)}`,
    );
  }
  console.log(`by array ${JSON.stringify(byArray)}`);
  console.log(`total ${total} B`);
}

function listFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
    e.isDirectory() ? listFiles(join(dir, e.name)) : [join(dir, e.name)],
  );
}

const mode = process.argv[2];
const manifest = loadManifest();

if (mode === "--probe") {
  probe(manifest);
} else if (mode === "--stats") {
  stats(generate(manifest).parsed);
} else if (mode === undefined || mode === "--check") {
  const { outputs } = generate(manifest);
  if (mode === "--check") {
    const bad = [];
    for (const [rel, want] of outputs) {
      const path = join(ROOT, rel);
      if (!existsSync(path) || readFileSync(path, "utf8") !== want)
        bad.push(rel);
    }
    for (const path of listFiles(join(ROOT, OUT_C))) {
      const rel = relative(ROOT, path);
      if (!outputs.has(rel)) bad.push(`${rel} (not generated)`);
    }
    if (bad.length > 0)
      die(`out of date, run \`mise run fonts:gen\`:\n  ${bad.join("\n  ")}`);
    console.log(`fonts: ${outputs.size} generated files match`);
  } else {
    // Drop files the manifest no longer produces, then write.
    for (const path of listFiles(join(ROOT, OUT_C))) {
      if (!outputs.has(relative(ROOT, path))) rmSync(path);
    }
    // An unchanged file is left alone: app:dev restarts the daemon on any write under app/src-tauri/.
    let written = 0;
    for (const [rel, content] of outputs) {
      const path = join(ROOT, rel);
      if (existsSync(path) && readFileSync(path, "utf8") === content) continue;
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      written++;
    }
    console.log(`fonts: wrote ${written} of ${outputs.size} files`);
  }
} else {
  die(`unknown option ${mode}`);
}
